"""
datapilot.mcp_servers.reports — MCP server for deliverables (stdio transport).

Turns analysis into deliverables for stakeholders:
  create_chart -> a PNG bar or line chart (matplotlib, no screen needed)
  write_report -> a markdown report file that can embed those charts
  list_reports -> what has been produced so far

Design lesson: the LLM never draws pixels. It passes DATA (labels + values)
and the tool renders it. Tools do the precise work; the model decides what to show.
"""
import re
from datetime import datetime
from typing import Literal

import matplotlib
matplotlib.use("Agg")                 # render to files, never open a window
import matplotlib.pyplot as plt       # noqa: E402
from mcp.server.fastmcp import FastMCP  # noqa: E402

from datapilot import settings  # noqa: E402

mcp = FastMCP("reports", log_level="WARNING")


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:60] or "untitled"


@mcp.tool()
def create_chart(title: str, chart_type: Literal["bar", "line"], labels: list[str],
                 values: list[float], y_label: str = "") -> str:
    """Create a PNG chart from data. labels = x-axis categories or dates, values = numbers
    (same length). Returns the file path, to reference in a report as ![title](path)."""
    if len(labels) != len(values):
        return f"Error: {len(labels)} labels but {len(values)} values; they must match."
    if not labels:
        return "Error: no data to plot."
    charts_dir = settings.REPORTS_DIR / "charts"
    charts_dir.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(9, 4.5), dpi=120)
    if chart_type == "bar":
        ax.bar(labels, values, color="#4C72B0")
    else:
        ax.plot(labels, values, marker="o", color="#4C72B0")
    ax.set_title(title, fontsize=13, loc="left")
    ax.set_ylabel(y_label)
    ax.spines[["top", "right"]].set_visible(False)
    ax.grid(axis="y", alpha=0.3)
    if len(labels) > 8:
        plt.xticks(rotation=45, ha="right")
    fig.tight_layout()
    path = charts_dir / f"{slugify(title)}.png"
    fig.savefig(path)
    plt.close(fig)
    return str(path)


@mcp.tool()
def write_report(title: str, markdown: str) -> str:
    """Save a markdown report for stakeholders (summary, numbers, charts, data caveats).
    Returns the file path."""
    settings.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y-%m-%d")
    path = settings.REPORTS_DIR / f"{stamp}-{slugify(title)}.md"
    header = f"# {title}\n\n_Generated by DataPilot on {stamp}_\n\n"
    path.write_text(header + markdown, encoding="utf-8")
    return str(path)


@mcp.tool()
def list_reports() -> list[str]:
    """List the reports and charts already produced."""
    root = settings.REPORTS_DIR
    if not root.exists():
        return []
    return sorted(str(p.relative_to(root)) for p in root.rglob("*") if p.is_file())


def main():
    mcp.run(transport="stdio")


if __name__ == "__main__":
    main()