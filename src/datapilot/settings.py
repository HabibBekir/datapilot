"""
datapilot.settings — every setting of the project, read once from the environment.

Values come from the .env file (see .env.example), with safe defaults.
Import what you need:  from datapilot import settings  ->  settings.WAREHOUSE_DB
"""
import os
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()  # reads .env into environment variables

# --- LLM (Ollama, local and free)
OLLAMA_MODEL = os.getenv("OLLAMA_MODEL", "qwen3:8b")
OLLAMA_NUM_CTX = int(os.getenv("OLLAMA_NUM_CTX", "16384"))
OLLAMA_DISABLE_THINKING = os.getenv("OLLAMA_DISABLE_THINKING", "true").lower() == "true"

# --- Local storage (git-ignored)
DATA_DIR = Path(os.getenv("DATAPILOT_DATA_DIR", "data")).resolve()
DATA_DIR.mkdir(parents=True, exist_ok=True)

WAREHOUSE_DB = DATA_DIR / "warehouse.db"   # company data, generated by warehouse.seed
METRICS_DB = DATA_DIR / "metrics.db"       # metrics catalog (semantic layer)
MEMORY_DB = DATA_DIR / "memory.db"         # conversation checkpoints
REPORTS_DIR = DATA_DIR / "reports"         # charts and markdown reports

# --- Metrics catalog MCP server (HTTP)
METRICS_HOST = os.getenv("METRICS_HOST", "127.0.0.1")
METRICS_PORT = int(os.getenv("METRICS_PORT", "8765"))
METRICS_URL = f"http://{METRICS_HOST}:{METRICS_PORT}/mcp"